def fmt(x):
    return f"{x:.1f}"


def top_five_note(ranked):
    """A presentation sentence that is true for whatever top five the data produces (method unchanged)."""
    top = ranked[:5]
    by_i = sorted(top, key=lambda r: -r["axes"]["intelligence"])
    lead = top[0]
    parts = [f"{r['display'].split(' (')[0]} {fmt(r['axes']['intelligence'])}" for r in by_i]
    text = f"Intelligence among the top five: {', '.join(parts)}."
    jev = next((r for r in ranked if r["key"] == "jev-1.13.0"), None)
    if jev is not None:
        above = [r for r in top if r["key"] != "jev-1.13.0" and r["axes"]["intelligence"] > jev["axes"]["intelligence"]]
        if above:
            text += (f" Jev 1.13.0 ({fmt(jev['axes']['intelligence'])}, rank {jev['rank']}) is out-reasoned by "
                     f"{['no', 'one', 'two', 'three', 'four', 'five'][len(above)]} of them.")
    if by_i[0]["key"] == lead["key"]:
        text += f" {lead['display'].split(' (')[0]} leads both the JevBench Score and Intelligence among the top five."
    best = max(ranked, key=lambda r: r["axes"]["intelligence"])
    if best["rank"] > 5:
        behind = [a for a in ("speed", "cost", "calibration") if best["axes"][a] < min(r["axes"][a] for r in top)]
        why = f", held back by its {' and '.join(a.capitalize() for a in behind)}" if behind else ""
        text += (f" Rows outside the top five reason better still (up to {fmt(best['axes']['intelligence'])}, "
                 f"{best['display'].split(' (')[0]}, rank {best['rank']}){why}.")
    text += " JevBench weighs the four axes equally; sort by Intelligence for raw reasoning."
    return text


def capability_top_keys(rows):
    """The signed 2x Jev class filter and Capability order used in the preview."""
    jev = next(r for r in rows if r["key"] == "jev-1.13.0")
    jev_lat = jev["speed"]["p50_s_adjusted"]
    speed_floor = jev["axes"]["speed"] - 20 * math.log10(2)
    def eligible(row):
        axes, cost, speed = row.get("axes") or {}, row.get("cost") or {}, row.get("speed") or {}
        latency = speed.get("p50_s_adjusted")
        return (row["ranked"] and axes.get("intelligence") is not None and axes.get("calibration") is not None
                and cost.get("usd_per_1000") is not None
                and cost["usd_per_1000"] <= 2 * jev["cost"]["usd_per_1000"]
                and (latency <= 2 * jev_lat if latency is not None else axes["speed"] >= speed_floor))
    return [r["key"] for r in sorted((r for r in rows if eligible(r)),
                                      key=lambda r: -(r["axes"]["intelligence"] + r["axes"]["calibration"]) / 2)[:5]]


def candidate_sha256(rows, footnotes, pending_prices, pending_provenance, held, headline):
    payload = {"systems": sorted(rows, key=lambda r: r["key"]), "footnotes": footnotes,
               "pricing_review_pending": pending_prices,
               "provenance_review_pending": pending_provenance,
               "measured_unranked_holds": held,
               "capability_headline_top_five": headline,
               "composite_top_five": [r["key"] for r in rows if r["ranked"]][:5]}
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"),
                           ensure_ascii=False, allow_nan=False).encode()
    return hashlib.sha256(canonical).hexdigest()


def verify_approval_receipt(path, digest, composite_top, capability_top):
    """Bind Florian's actual reply and the sent preview to this exact candidate."""
    if not path:
        raise ValueError("Cannot finalize v1.4.3: changed top five needs Florian's approval receipt")
    receipt_path = Path(path).resolve()
    if not receipt_path.is_file() or not receipt_path.is_relative_to(APPROVAL_RECEIPTS_DIR.resolve()) \
            or receipt_path.suffix != ".json":
        raise ValueError("Approval receipt must be a JSON file under release/receipts")
    receipt = read(receipt_path)
    required = {"approved_by": "Florian", "decision": "approved", "source": "Telegram",
                "candidate_sha256": digest, "preview_sha256": sha(PREVIEW_HTML),
                "composite_top_five": composite_top, "capability_top_five": capability_top}
    for field, expected in required.items():
        if receipt.get(field) != expected:
            raise ValueError(f"Approval receipt {field} does not match the final candidate")
    for field in ("request_message_id", "reply_message_id", "approved_utc"):
        if not isinstance(receipt.get(field), str) or not receipt[field].strip():
            raise ValueError(f"Approval receipt lacks {field}")
    if not receipt["reply_message_id"].isdigit() or \
            receipt["reply_message_id"] == receipt["request_message_id"]:
        raise ValueError("Approval receipt has no distinct Telegram reply message ID")
    try:
        approved_time = dt.datetime.fromisoformat(receipt["approved_utc"].replace("Z", "+00:00"))
        if approved_time.tzinfo is None:
            raise ValueError("naive date")
    except ValueError as exc:
        raise ValueError("Approval receipt has invalid approved_utc") from exc
    images = receipt.get("preview_images")
    if not isinstance(images, list) or len(images) != 1:
        raise ValueError("Approval receipt must bind the one photo sent with the approval request")
    for entry in images:
        if not isinstance(entry, dict) or not isinstance(entry.get("path"), str):
            raise ValueError("Approval receipt preview_images entry is invalid")
        image_path = (ROOT.parent / entry["path"]).resolve()
        if not image_path.is_file() or not image_path.is_relative_to(ROOT.parent.resolve()) \
                or image_path.suffix.lower() != ".png" or sha(image_path) != entry.get("sha256"):
            raise ValueError("Approval receipt preview image hash does not match")
        if not receipt["request_message_id"].isdigit():
            raise ValueError("Approval receipt request_message_id must be a Telegram message ID")
        sent = [json.loads(line) for line in NOTIFY_LOG.read_text().splitlines()
                if line.strip() and '"message_id"' in line]
        matching = [item for item in sent
                    if item.get("message_id") == int(receipt["request_message_id"])
                    and item.get("sent") is True and item.get("level") == "now"
                    and item.get("photo") and Path(item["photo"]).resolve() == image_path
                    and "JevBench v1.4.3" in item.get("text", "")]
        if len(matching) != 1:
            raise ValueError("Approval photo is not tied to the sent notify message")
        if image_path.stat().st_mtime > matching[0]["ts"]:
            raise ValueError("Approval preview image changed after the notify send")
        if approved_time.timestamp() < matching[0]["ts"]:
            raise ValueError("Approval reply predates the preview request")
    return {"path": receipt_path.name, "sha256": sha(receipt_path),
            "request_message_id": receipt["request_message_id"],
            "reply_message_id": receipt["reply_message_id"]}


def policy_cost(list_cost, base_reference_cost):
    """USD/1,000 decisions after the 30-day list-price check and base-model floor.

    Pass None for an ineligible/missing list price or an unavailable base reference.
    Both costs must already use this system's measured input and output tokens.
    """
    values = [v for v in (list_cost, base_reference_cost) if v is not None]
    if any(not math.isfinite(v) or v < 0 for v in values):
        raise ValueError("Non-finite or negative price cost")
    return max(values) if values else None


