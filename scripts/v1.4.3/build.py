def check_pair(src, row):
    """The owner's aggregate source must be the projection of its full-protocol ROW and reproduce its release score."""
    key = src["key"]
    assert src["key"] == row["key"], (src["key"], row["key"])
    for f in ("v130", "public_acc", "sealed_acc"):
        assert src[f] == row[f], (key, f)
    assert src["v14"]["axes"] == row["v14"]["axes"], key
    s = row["sealed"]
    # Every sealed item must be attempted. Invalid/refused answers still count as wrong,
    # as they do for ranked rows already published in v1.4.2.
    assert (s["n"] == s["attempted"] == 308
            and s["answered_valid"] + s["failed_or_invalid"] == 308), (key, "sealed run incomplete")
    counts = row["measurements"]["scope_counts"]
    assert set(counts) == {"public-source", "historical-private", "current-sealed"}, (key, counts)
    assert all(type(value) is int and value >= 0 for value in counts.values()), (key, counts)
    assert counts == {"public-source": 377, "historical-private": 157,
                      "current-sealed": 308}, (key, counts)
    assert row["release_score"]["scoring_module_sha256"] == COMPOSITE_SHA256, key
    _, value = score.score_from_comparison(src)
    assert value == row["release_score"]["score"], (key, value, row["release_score"]["score"])
    assert abs(row["measurements"]["cost"]["cost_axis"] - src["v130"]["axes"]["cost"]) < 1e-9, key
    assert abs(row["measurements"]["old_speed"]["axis"] - src["v130"]["axes"]["speed"]) < 1e-9, key
    # A label-only system has no probability distribution to calibrate. Its
    # official scorer assigns a zero axis, while the public aggregate keeps
    # the absent probability measurements as null.
    old, cand = src["v130"]["axes"]["calibration"], src["v14"]["axes"]["calibration"]
    if s["label_only"]:
        assert old is None and cand is None and s["calibration"] is None, key
        assert src["sealed"]["risk_coverage"] is None and src["sealed"]["ece"] is None, key
        assert not src["ranked"] and not row["ranked"], key
        assert row["release_score"]["axes"]["calibration"] == 0, key
    else:
        assert abs(old + (s["calibration"] - old) * BLEND - cand) < 1e-9, (key, "calibration blend")


