            expected_input_sha = ALLOWED_INPUT_SHA256.get(src["key"], FULL_INPUT_SHA256)
            assert row.get("input_sha256") == expected_input_sha, (src["key"], "unexpected blind input")
            if src["key"] in DERIVED_INPUT_PINS:
                expected_agg_sha, expected_token_sha = DERIVED_INPUT_PINS[src["key"]]
